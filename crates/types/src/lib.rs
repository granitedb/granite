//! Type system, encodings and expressions.
//!
//! [`Type`] describes a column, [`Value`] holds one typed value in memory.
//! [`key`] is the order-preserving key encoding and [`storage`] the
//! fixed-width storage representation; both are part of the on-disk format
//! and are specified byte by byte in document 03 section 2. [`arith`] is the
//! checked arithmetic, comparison and casts of the numeric types.

use granite_base::constants::FORMAT;

pub mod arith;
pub mod key;
pub mod storage;

/// An unsigned 256-bit integer. The derived order is the numeric order.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Default)]
pub struct U256 {
    pub hi: u128,
    pub lo: u128,
}

/// A signed 256-bit two's complement integer: `hi` holds the sign. The
/// derived order (signed `hi`, then unsigned `lo`) is the numeric order.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Default)]
pub struct I256 {
    pub hi: i128,
    pub lo: u128,
}

impl U256 {
    pub const MIN: Self = Self { hi: 0, lo: 0 };
    pub const MAX: Self = Self {
        hi: u128::MAX,
        lo: u128::MAX,
    };
}

impl I256 {
    pub const MIN: Self = Self {
        hi: i128::MIN,
        lo: 0,
    };
    pub const MAX: Self = Self {
        hi: i128::MAX,
        lo: u128::MAX,
    };
}

/// Fractional-second digits of a Timestamp or Duration: the value counts
/// units of 10^-p seconds.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum TimePrecision {
    Seconds,
    Millis,
    Micros,
    Nanos,
}

/// The type of a column (document 03 section 2), without the composite types.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum Type {
    U8,
    U16,
    U32,
    U64,
    U128,
    U256,
    I8,
    I16,
    I32,
    I64,
    I128,
    I256,
    /// Fixed point: the value is `mantissa / 10^scale`, with at most
    /// `precision` digits. The mantissa is an i32, i64, i128 or i256 by precision.
    Decimal {
        precision: u8,
        scale: u8,
    },
    F32,
    F64,
    Bool,
    /// Days since 1970-01-01.
    Date,
    /// Units of 10^-p seconds since 1970-01-01T00:00:00 UTC.
    Timestamp(TimePrecision),
    /// Units of 10^-p seconds.
    Duration(TimePrecision),
    Uuid,
    /// Time-ordered id generated by the client library; compared as a u128.
    Id128,
    /// UTF-8 text of at most `max` bytes, compared byte by byte.
    String {
        max: u32,
    },
    /// At most `max` bytes.
    Bytes {
        max: u32,
    },
    /// Exactly this many bytes.
    FixedBytes(u32),
    /// A declared value's index, `0..=max`.
    Enum8 {
        max: u8,
    },
    /// A declared value's index, `0..=max`.
    Enum16 {
        max: u16,
    },
    Nullable(Box<Type>),
    /// A storage hint; the logical type, value and key encoding are the inner type's.
    LowCardinality(Box<Type>),
}

/// One value in memory. Which variant goes with which [`Type`] is given by
/// [`Type::check`]; `Null` belongs only to `Nullable`.
#[derive(Clone, Debug, PartialEq)]
pub enum Value {
    U8(u8),
    U16(u16),
    U32(u32),
    U64(u64),
    U128(u128),
    U256(U256),
    I8(i8),
    I16(i16),
    I32(i32),
    I64(i64),
    I128(i128),
    I256(I256),
    /// Mantissa of a Decimal with precision 1 to 9.
    Decimal32(i32),
    /// Mantissa of a Decimal with precision 10 to 18.
    Decimal64(i64),
    /// Mantissa of a Decimal with precision 19 to 38.
    Decimal128(i128),
    /// Mantissa of a Decimal with precision 39 to 76.
    Decimal256(I256),
    F32(f32),
    F64(f64),
    Bool(bool),
    Date(i32),
    Timestamp(i64),
    Duration(i64),
    Uuid([u8; 16]),
    Id128(u128),
    String(String),
    Bytes(Vec<u8>),
    FixedBytes(Vec<u8>),
    Enum8(u8),
    Enum16(u16),
    Null,
}

/// Typed errors of the type system and its encodings.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum Error {
    /// The type itself is invalid (decimal precision or scale out of range,
    /// fixed bytes empty or longer than a row, nested Nullable or LowCardinality).
    InvalidType,
    /// The value's variant does not belong to the type.
    Mismatch,
    /// Floats and nullable types cannot be key columns.
    NotAllowedInKey,
    /// A String or Bytes value is longer than its type's max, or a FixedBytes
    /// value has the wrong length.
    Length { len: u64, max: u64 },
    /// An enum index above the declared values.
    UnknownEnumValue,
    /// Bytes that are not valid UTF-8 for a String.
    InvalidUtf8,
    /// An encoded primary key longer than `FORMAT.primary_key_size_max`.
    KeyTooLarge { size: u64 },
    /// The number of key values differs from the number of key columns.
    ColumnCount,
    /// Bytes that no value of the type encodes to.
    Malformed,
    /// The type has no fixed-width storage representation.
    NotFixedWidth,
    /// An arithmetic result or a cast value outside the range of its type
    /// ([`arith`]), or a Decimal(P, S) value with more than P digits.
    Overflow,
    /// A division or remainder by zero ([`arith`]).
    DivisionByZero,
    /// A result with more fractional digits, or significant bits, than its
    /// type holds, or NaN cast to a non-float type ([`arith`]).
    LossOfPrecision,
}

impl Type {
    /// Checks the type's own parameters.
    pub fn validate(&self) -> Result<(), Error> {
        let ok = match self {
            Type::Decimal { precision, scale } => {
                (1..=FORMAT.decimal_precision_max).contains(&u64::from(*precision))
                    && scale <= precision
            }
            Type::FixedBytes(n) => (1..=FORMAT.row_size_max).contains(&u64::from(*n)),
            Type::Nullable(inner) if matches!(inner.logical(), Type::Nullable(_)) => false,
            Type::LowCardinality(inner) if matches!(**inner, Type::LowCardinality(_)) => false,
            Type::Nullable(inner) | Type::LowCardinality(inner) => return inner.validate(),
            _ => true,
        };
        if ok { Ok(()) } else { Err(Error::InvalidType) }
    }

    /// The type without a LowCardinality hint.
    fn logical(&self) -> &Type {
        match self {
            Type::LowCardinality(inner) => inner,
            other => other,
        }
    }

    /// Checks that `value` is a valid value of this type: the right variant,
    /// lengths within bounds, enum indexes declared, decimal mantissas of at
    /// most P digits (else `Overflow`), text valid UTF-8 (by construction of
    /// `String`).
    pub fn check(&self, value: &Value) -> Result<(), Error> {
        self.validate()?;
        let length = |len: usize, max: u32, exact: bool| {
            let (len, max) = (len64(len), u64::from(max));
            if len > max || (exact && len != max) {
                Err(Error::Length { len, max })
            } else {
                Ok(())
            }
        };
        use Value as V;
        match (self.logical(), value) {
            (Type::Nullable(_), V::Null) => Ok(()),
            (Type::Nullable(inner), v) => inner.check(v),
            (Type::String { max }, V::String(s)) => length(s.len(), *max, false),
            (Type::Bytes { max }, V::Bytes(b)) => length(b.len(), *max, false),
            (Type::FixedBytes(n), V::FixedBytes(b)) => length(b.len(), *n, true),
            (Type::Enum8 { max }, V::Enum8(i)) if i > max => Err(Error::UnknownEnumValue),
            (Type::Enum16 { max }, V::Enum16(i)) if i > max => Err(Error::UnknownEnumValue),
            (Type::Decimal { precision, .. }, v) => match (decimal_width(*precision), v) {
                (4, V::Decimal32(_))
                | (8, V::Decimal64(_))
                | (16, V::Decimal128(_))
                | (32, V::Decimal256(_)) => arith::digits(*precision, v),
                _ => Err(Error::Mismatch),
            },
            (Type::U8, V::U8(_))
            | (Type::U16, V::U16(_))
            | (Type::U32, V::U32(_))
            | (Type::U64, V::U64(_))
            | (Type::U128, V::U128(_))
            | (Type::U256, V::U256(_))
            | (Type::I8, V::I8(_))
            | (Type::I16, V::I16(_))
            | (Type::I32, V::I32(_))
            | (Type::I64, V::I64(_))
            | (Type::I128, V::I128(_))
            | (Type::I256, V::I256(_))
            | (Type::F32, V::F32(_))
            | (Type::F64, V::F64(_))
            | (Type::Bool, V::Bool(_))
            | (Type::Date, V::Date(_))
            | (Type::Timestamp(_), V::Timestamp(_))
            | (Type::Duration(_), V::Duration(_))
            | (Type::Uuid, V::Uuid(_))
            | (Type::Id128, V::Id128(_))
            | (Type::Enum8 { .. }, V::Enum8(_))
            | (Type::Enum16 { .. }, V::Enum16(_)) => Ok(()),
            _ => Err(Error::Mismatch),
        }
    }

    /// [`Type::check`] of a decoded value, where a decimal of more than P
    /// digits is `Malformed`: no value encodes to its bytes.
    fn check_decoded(&self, value: &Value) -> Result<(), Error> {
        match self.check(value) {
            Err(Error::Overflow) => Err(Error::Malformed),
            other => other,
        }
    }
}

/// Bytes of a decimal mantissa by precision: i32 to 9 digits, i64 to 18,
/// i128 to 38, i256 above.
pub fn decimal_width(precision: u8) -> u32 {
    match precision {
        0..=9 => 4,
        10..=18 => 8,
        19..=38 => 16,
        _ => 32,
    }
}

/// A length as a u64, which holds every `usize` of the supported platforms.
fn len64(len: usize) -> u64 {
    u64::try_from(len).expect("usize fits u64")
}

/// A u32 length as a `usize`, which holds every u32 on the supported platforms.
fn usize32(n: u32) -> usize {
    usize::try_from(n).expect("u32 fits usize")
}

/// The canonical NaN of f32: positive, quiet, zero payload.
pub const CANONICAL_NAN_F32: u32 = 0x7fc0_0000;
/// The canonical NaN of f64: positive, quiet, zero payload.
pub const CANONICAL_NAN_F64: u64 = 0x7ff8_0000_0000_0000;

/// `x`, with every NaN replaced by the canonical NaN.
pub fn canonical_f32(x: f32) -> f32 {
    if x.is_nan() {
        f32::from_bits(CANONICAL_NAN_F32)
    } else {
        x
    }
}

/// `x`, with every NaN replaced by the canonical NaN.
pub fn canonical_f64(x: f64) -> f64 {
    if x.is_nan() {
        f64::from_bits(CANONICAL_NAN_F64)
    } else {
        x
    }
}

/// Reads an encoding front to back, XOR-ing every byte with `mask`.
struct Reader<'a> {
    bytes: &'a [u8],
    pos: usize,
    mask: u8,
}

impl Reader<'_> {
    fn slice(&mut self, n: usize) -> Result<&[u8], Error> {
        let end = self.pos.checked_add(n).ok_or(Error::Malformed)?;
        let s = self.bytes.get(self.pos..end).ok_or(Error::Malformed)?;
        self.pos = end;
        Ok(s)
    }

    fn take_vec(&mut self, n: usize) -> Result<Vec<u8>, Error> {
        let mask = self.mask;
        Ok(self.slice(n)?.iter().map(|b| b ^ mask).collect())
    }

    fn take<const N: usize>(&mut self) -> Result<[u8; N], Error> {
        let mask = self.mask;
        let s = self.slice(N)?;
        Ok(std::array::from_fn(|i| s[i] ^ mask))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn i256_order_is_numeric() {
        let minus_one = I256 {
            hi: -1,
            lo: u128::MAX,
        };
        let one = I256 { hi: 0, lo: 1 };
        let big = I256 { hi: 1, lo: 0 };
        let order = [I256::MIN, minus_one, I256::default(), one, big, I256::MAX];
        assert!(order.windows(2).all(|w| w[0] < w[1]));
    }

    #[test]
    fn types_are_validated() {
        let max = FORMAT.decimal_precision_max as u8;
        let dec = |precision, scale| Type::Decimal { precision, scale }.validate();
        assert_eq!(dec(max, max), Ok(()));
        assert_eq!(dec(1, 0), Ok(()));
        assert_eq!(dec(0, 0), Err(Error::InvalidType));
        assert_eq!(dec(max + 1, 0), Err(Error::InvalidType));
        assert_eq!(dec(5, 6), Err(Error::InvalidType));
        assert_eq!(Type::FixedBytes(0).validate(), Err(Error::InvalidType));
        let row = FORMAT.row_size_max as u32;
        assert_eq!(Type::FixedBytes(row).validate(), Ok(()));
        assert_eq!(
            Type::FixedBytes(row + 1).validate(),
            Err(Error::InvalidType)
        );
        let nested = Type::Nullable(Box::new(Type::Nullable(Box::new(Type::U8))));
        assert_eq!(nested.validate(), Err(Error::InvalidType));
    }

    #[test]
    fn values_are_checked_against_types() {
        let s = Type::String { max: 3 };
        assert_eq!(s.check(&Value::String("abc".into())), Ok(()));
        assert_eq!(
            s.check(&Value::String("abcd".into())),
            Err(Error::Length { len: 4, max: 3 })
        );
        assert_eq!(
            Type::FixedBytes(2).check(&Value::FixedBytes(vec![1])),
            Err(Error::Length { len: 1, max: 2 })
        );
        assert_eq!(
            Type::Enum8 { max: 2 }.check(&Value::Enum8(3)),
            Err(Error::UnknownEnumValue)
        );
        let d = Type::Decimal {
            precision: 10,
            scale: 2,
        };
        assert_eq!(d.check(&Value::Decimal64(1)), Ok(()));
        assert_eq!(d.check(&Value::Decimal32(1)), Err(Error::Mismatch));
        assert_eq!(Type::U8.check(&Value::Null), Err(Error::Mismatch));
        let n = Type::Nullable(Box::new(Type::U8));
        assert_eq!(n.check(&Value::Null), Ok(()));
        assert_eq!(n.check(&Value::U8(1)), Ok(()));
    }
}
